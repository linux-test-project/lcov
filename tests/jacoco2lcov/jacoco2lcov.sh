# run <label> <expected exit status> <args>... -- run jacoco2lcov, keeping its
#  output in '<label>.log'.  Returns success when the exit status was the
#  expected one, so a caller which wants to look at the result can do that only
#  when the run went the way it was supposed to
run()
{
    local label=$1
    local expect=$2
    shift 2

    echo "$label: jacoco2lcov $*"
    $COVER ${EXEC_COVER} $JACOCO2LCOV_TOOL "$@" > $label.log 2>&1
    local rc=$?
    if [ $rc != $expect ] ; then
        fail $label "expected exit status $expect, got $rc:"
        cat $label.log
        return 1
    fi
    return 0
}

# expect_log <label> <pattern> -- the run said this
expect_log()
{
    if ! grep -q -- "$2" $1.log ; then
        fail $1 "expected '$2' in the output:"
        cat $1.log
    fi
}

# reject_log <label> <pattern> -- and did not say this
reject_log()
{
    if grep -q -- "$2" $1.log ; then
        fail $1 "did not expect '$2' in the output:"
        cat $1.log
    fi
}

# expect_data <label> <file> <pattern> -- the generated .info says this
expect_data()
{
    if ! grep -q -- "$3" $2 ; then
        fail $1 "expected '$3' in $2:"
        cat $2
    fi
}

# reject_data <label> <file> <pattern> -- and does not say this
reject_data()
{
    if grep -q -- "$3" $2 ; then
        fail $1 "did not expect '$3' in $2:"
        cat $2
    fi
}

# canonical_info <file> -- the coverage data in <file>, in an order which does
#  not depend on who wrote the file:  one section per source file, sorted, with
#  the coverpoints inside it sorted too, and the test name dropped.  Two files
#  which say the same thing about the same code produce the same text here.
#  Cmparison against xml2lcov's own output has to be rewritten by lcov's writer
#  so it gets the same order as jacoco2lcov produces.
canonical_info()
{
    perl -e 'my (%rec, $sf, @body);
             while (<>) {
                 next if /^TN:/;
                 if (/^SF:/) { $sf = $_; @body = (); next }
                 if (/^end_of_record/) { $rec{$sf} = join("", sort(@body)); next }
                 push(@body, $_);
             }
             foreach my $f (sort(keys(%rec))) { print($f, $rec{$f}) }' "$1"
}

# undocumented_options <label> -- the entries in the 'Tool options:' section of
#  the usage message which do not say whether the option is optional or
#  required, or do not say what it defaults to.  Checked this way rather than
#  by matching the text, which is prose and gets reworded:  what has to hold is
#  that every option says both of those things, not that it says them in any
#  particular words.  '--help' itself is exempt - it has no default
undocumented_options()
{
    perl -e '
        my ($in_section, $option, $text);
        my @undocumented;
        sub check
        {
            return unless defined($option);
            return if $option =~ /--help/;
            push(@undocumented, "$option: no optional/required marking")
                unless $text =~ /Optional|Required/;
            push(@undocumented, "$option: no default")
                unless $text =~ /Default:/;
        }
        while (<>) {
            if (!$in_section) {
                $in_section = 1 if /^Tool options:/;
                next;
            }
            last if /^Common options:/;
            #  an option entry starts with the option names, indented;  two of
            #   them in a row share the description which follows
            if (/^ +--?[a-zA-Z]/) {
                if (defined($option) && $text !~ /\S/) {
                    $option .= " $_";
                } else {
                    check();
                    ($option, $text) = ($_, "");
                }
                $option =~ s/\s+/ /g;
                $option =~ s/^ | $//g;
                next;
            }
            $text .= $_ if defined($option);
        }
        check();
        print(map("$_\n", @undocumented));
    ' < $1.log
}

# expect_java <label> <expected command line> -- the stub 'java' was run with
#  exactly this.  The temporary report name is replaced, because it is below the
#  temporary directory lcovutil made, whose name is different on every run -
#  which is the point of it.  A report which '--xml' asked to keep is named
#  something else, so it survives
expect_java()
{
    local actual=`sed -e 's,--xml [^ ]*/jacoco\.xml,--xml TMPXML,' fakejava.log`
    if [ "$actual" != "$2" ] ; then
        fail $1 "java command line is
  '$actual'
rather than
  '$2'"
    fi
}

