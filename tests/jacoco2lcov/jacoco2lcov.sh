# through a link in a directory which holds nothing else:  the xml2lcov which
#  runs is the one installed beside the script, because that is what 'installed
#  next to jacoco2lcov' means - there is nothing beside the link
JACOCO2LCOV_TOOL=linkdir/jacoco2lcov
