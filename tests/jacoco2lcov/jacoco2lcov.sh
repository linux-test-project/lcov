# On Windows, perl's '-x' answers from the file name extension rather than from
#  any permission, so an extensionless file is never executable there - and none
#  of the tools jacoco2lcov runs has an extension in an LCOV installation.  So
#  jacoco2lcov prefers a sibling with an extension Windows can run, and
#  otherwise runs the file it found anyway.  'LCOV_ASSUME_WINDOWS' is the
#  test hook which reaches that decision from here;  what a run which reached it
#  did is visible in which command it ran, or failed to run
export LCOV_ASSUME_WINDOWS=1

# a '.bat' beside the script is what an installation which wrapped the script
#  for Windows leaves, and the wrapper is the thing to run.  This one forwards to
#  the real xml2lcov, so the whole translation runs through it
XML2LCOV=`readlink -f ${XML2LCOV_TOOL}`
mkdir -p wintools
printf 'not an executable file\n' > wintools/xml2lcov
cat > wintools/xml2lcov.bat << EOF
#!/bin/bash
exec $XML2LCOV "\$@"
EOF
chmod 755 wintools/xml2lcov.bat
if run winbat 0 -o winbat.info -s src -c bin -jar $JAR --java ./fakejava -v \
       --xml2lcov wintools/xml2lcov test.exec ; then
    expect_log winbat 'wintools/xml2lcov.bat --format jacoco'
    expect_data winbat winbat.info '^SF:src/com/example/Widget.java$'
fi

# with no such sibling, the file itself is used, however little -x thinks of it.
#  Here that fails, because this file really is not executable - but it fails at
#  the point of running it, which is the point:  a Windows run gets this far,
#  and an LCOV installation there is nothing but files -x rejects
if run winplain 1 -o winplain.info -s src -c bin -jar $JAR --java ./fakejava \
       --xml2lcov nominal.xml test.exec ; then
    expect_log winplain "unable to execute 'nominal.xml'"
    reject_log winplain 'is not an executable file'
fi

# a sibling which -x rejects as well is no better than the script:  the script
#  is what gets run, which is what the failure names
mkdir -p winnobat
printf 'not an executable file\n' > winnobat/xml2lcov
printf 'not an executable file either\n' > winnobat/xml2lcov.bat
chmod 644 winnobat/xml2lcov winnobat/xml2lcov.bat
if run winbadbat 1 -o winbadbat.info -s src -c bin -jar $JAR \
       --java ./fakejava --xml2lcov winnobat/xml2lcov test.exec ; then
    expect_log winbadbat "unable to execute 'winnobat/xml2lcov'"
fi

# and a name which names nothing is still the usage error it always was:  the
#  hack takes a file which is there and cannot be shown to be runnable, not a
#  file which is not there
if run winnotool 1 -o winnotool.info -s src -c bin -jar $JAR \
       --java ./fakejava --xml2lcov nosuchtool test.exec ; then
    expect_log winnotool "'nosuchtool' is not an executable file"
    expect_log winnotool "use '--xml2lcov'"
fi

unset LCOV_ASSUME_WINDOWS

# ---------------------------------------------------------------------------
# 16. Windows path names, on a perl whose path syntax is Unix's
# ---------------------------------------------------------------------------

# A git-bash, MSYS or Cygwin perl has Unix path semantics and knows nothing of
#  drive letters, so 'Z:\dir\file' - which is what a Windows caller writes, in
#  an option, in an environment variable or in the name it invokes the script by
#  - names nothing that perl can open.  The drives are mounted in such an
#  installation, so the same file has a name it does understand, and jacoco2lcov
#  translates every path it is handed to that name - its own options here, and
#  the common ones in lcovutil.pm, which is where the translation itself lives.
#  'LCOV_DRIVE_MOUNT' is the test hook:  it says which directory to look for the
#  drives in, and turns the translation on, which is what lets any of this run
#  here.
# The fixtures below are a 'Z:' drive holding what a run needs - the jar, a java,
#  sources, classes, a plugin, execution data, a root directory to work in, and
#  an installation of the tools themselves
WINMOUNT=`pwd`/winmount
export LCOV_DRIVE_MOUNT=$WINMOUNT
mkdir -p $WINMOUNT/z/jacoco/lib $WINMOUNT/z/javahome/bin $WINMOUNT/z/classes \
    $WINMOUNT/z/out $WINMOUNT/z/bin
cp $JAR $WINMOUNT/z/jacoco/lib/jacococli.jar
cp fakejava $WINMOUNT/z/javahome/bin/java
printf 'not really a class file\n' > $WINMOUNT/z/classes/Widget.class
cp -r src $WINMOUNT/z/src
cp -r plugins $WINMOUNT/z/plugins
cp -r droot $WINMOUNT/z/droot
cp test.exec $WINMOUNT/z/test.exec
XML2LCOV=`readlink -f ${XML2LCOV_TOOL}`
ln -s $XML2LCOV $WINMOUNT/z/bin/xml2lcov
#  the 'winself' case below runs a copy of the script from this bin directory,
#   and a copy of the script loads its modules from '../lib' of wherever it was
#   found - so this installation needs that directory too
ln -s `readlink -f $LCOV_HOME/lib` $WINMOUNT/z/lib

# the jar and the java, written both ways a Windows path can be written:  the
#  separator is a backslash or a forward slash, and either of them arrives
if run winjar 0 -o winjar.info -s src -c bin -v \
       --jar 'Z:\jacoco\lib\jacococli.jar' --java 'Z:/javahome/bin/java' \
       test.exec ; then
    expect_java winjar "$WINMOUNT/z/javahome/bin/java -jar $WINMOUNT/z/jacoco/lib/jacococli.jar report test.exec --classfiles bin --sourcefiles src --xml TMPXML"
    expect_data winjar winjar.info '^SF:src/com/example/Widget.java$'
fi

# the source and class directories, the execution data and the output file:  the
#  translated names are what JaCoCo is told to use, because they are the names
#  which name those files here
if run windirs 0 -o 'Z:/out/windirs.info' -s 'Z:\src' -c 'Z:\classes' -v \
       --jar 'Z:\jacoco\lib\jacococli.jar' --java ./fakejava 'Z:\test.exec' ; then
    expect_java windirs "./fakejava -jar $WINMOUNT/z/jacoco/lib/jacococli.jar report $WINMOUNT/z/test.exec --classfiles $WINMOUNT/z/classes --sourcefiles $WINMOUNT/z/src --xml TMPXML"
    expect_data windirs $WINMOUNT/z/out/windirs.info "^SF:$WINMOUNT/z/src/com/example/Widget.java\$"
fi

# a plugin root is expanded after it is translated, so the directories it
#  contributes are named the way this perl can use them too - and '--xml' names
#  the report to keep in the same way
if run winplugin 0 -o winplugin.info -p 'Z:\plugins\pluginA' \
       --xml 'Z:/out/winplugin.xml' --jar 'Z:\jacoco\lib\jacococli.jar' \
       --java ./fakejava -v test.exec ; then
    expect_java winplugin "./fakejava -jar $WINMOUNT/z/jacoco/lib/jacococli.jar report test.exec --classfiles $WINMOUNT/z/plugins/pluginA/target/classes --sourcefiles $WINMOUNT/z/plugins/pluginA/src/main/java --xml $WINMOUNT/z/out/winplugin.xml"
    if [ ! -f $WINMOUNT/z/out/winplugin.xml ] ; then
        fail winplugin 'the XML report was not kept where it was asked for'
    fi
fi

# the tools to run are paths as well
if run wintool 0 -o wintool.info -s src -c bin -v \
       --xml2lcov 'Z:/bin/xml2lcov' --jar 'Z:\jacoco\lib\jacococli.jar' \
       --java ./fakejava test.exec ; then
    expect_log wintool "$WINMOUNT/z/bin/xml2lcov --format jacoco"
    expect_data wintool wintool.info '^SF:src/com/example/Widget.java$'
fi

# the separators do not have to be consistent, and a path does not have to name
#  a drive at all:  a backslash is the Windows separator wherever it appears, so
#  a relative Windows path and a UNC name - which is '//host/share/...' on these
#  perls - are usable once the separators are turned around.  'winmount\z\src' is
#  the relative one, and it names the same sources as the runs above
if run winmixed 0 -o winmixed.info -s 'winmount\z\src' -c 'Z:\classes' -v \
       --jar 'Z:\jacoco/lib\jacococli.jar' --java ./fakejava test.exec ; then
    expect_java winmixed "./fakejava -jar $WINMOUNT/z/jacoco/lib/jacococli.jar report test.exec --classfiles $WINMOUNT/z/classes --sourcefiles winmount/z/src --xml TMPXML"
    expect_data winmixed winmixed.info '^SF:winmount/z/src/com/example/Widget.java$'
fi

# and so is the root directory to work in, which everything else is relative to.
#  The stub is told where to write from here, because it runs in that directory
SAVED_STUB_LOG=$STUB_LOG
export STUB_LOG=`pwd`/fakejava.log
export STUB_REPORT=`pwd`/nominal.xml
if run windroot 0 -d 'Z:\droot' -o windroot.info -s src/main/java \
       -c target/classes -v --jar 'Z:\jacoco\lib\jacococli.jar' \
       --java $WINMOUNT/z/javahome/bin/java execdir/second.exec ; then
    expect_log windroot "working in root directory '$WINMOUNT/z/droot'"
    expect_data windroot $WINMOUNT/z/droot/windroot.info '^SF:src/main/java/com/example/Widget.java$'
fi
export STUB_LOG=$SAVED_STUB_LOG
STUB_REPORT=

# a drive this installation has not mounted has no name to be translated to, so
#  it is left as it stands and the drive the user named is what the complaint
#  names
if run winnodrive 1 -o winnodrive.info -s src -c bin \
       --jar 'Q:\jacoco\lib\jacococli.jar' --java ./fakejava test.exec ; then
    expect_log winnodrive "'Q:/jacoco/lib/jacococli.jar' is not a readable file"
fi

# a UNC name is a path on these perls too, written '//host/share/...'.  There is
#  no such share here, so what this shows is the name which was looked for
if run winunc 1 -o winunc.info -s src -c bin \
       --jar '\\build01\share\jacoco\jacococli.jar' --java ./fakejava \
       test.exec ; then
    expect_log winunc "'//build01/share/jacoco/jacococli.jar' is not a readable file"
fi

# the name the script was invoked by is translated too - which is what decides
#  where the tools it runs come from, and what the failing Windows run got
#  wrong.  This one is a copy of the script under the mounted drive, invoked by
#  the drive name:  the xml2lcov which runs is the one beside the copy.
#  Perl opens the script itself, so the name has to name something from here as
#  well - hence the link;  and coverage is off, because Devel::Cover would
#  record a second file for a second path to the same script
SAVED_JACOCO2LCOV_TOOL=$JACOCO2LCOV_TOOL
SAVED_COVER=$COVER
WINSELF='Z:\bin\jacoco2lcov'
cp `readlink -f $JACOCO2LCOV_TOOL` $WINMOUNT/z/bin/jacoco2lcov
chmod 755 $WINMOUNT/z/bin/jacoco2lcov
ln -s $WINMOUNT/z/bin/jacoco2lcov "$WINSELF"
COVER=
JACOCO2LCOV_TOOL="perl $WINSELF"
if run winself 0 -o winself.info -s src -c bin -v \
       --jar 'Z:\jacoco\lib\jacococli.jar' --java ./fakejava test.exec ; then
    expect_log winself "$WINMOUNT/z/bin/xml2lcov --format jacoco"
    expect_java winself "./fakejava -jar $WINMOUNT/z/jacoco/lib/jacococli.jar report test.exec --classfiles bin --sourcefiles src --xml TMPXML"
    expect_data winself winself.info '^SF:src/com/example/Widget.java$'
    #  and the drive name reached neither the messages nor the temporary
    #   directory the script made for itself
    reject_log winself 'Z:'
fi
JACOCO2LCOV_TOOL=$SAVED_JACOCO2LCOV_TOOL
COVER=$SAVED_COVER

unset LCOV_DRIVE_MOUNT

# ---------------------------------------------------------------------------
# 17. --version-script
# ---------------------------------------------------------------------------

# A JaCoCo report does not say which version of the source it describes, so the
#  only version there can be is the one the callback computes from the source -
#  and computing it as the translated data is read back in is what
#  'compute_file_version' asks for.  jacoco2lcov turns that on for itself when a
#  version script is named:  a flag which quietly wrote no VER: record would be
#  no use, because the report step computes a version for the source it reads
#  and stops when the data it is shown has nothing to compare against.
#  'echo' stands in for a version script - it prints the name it is handed,
#  which is enough to show whose version was computed
if run version 0 -o version.info -s src -c bin -jar $JAR --java ./fakejava \
       --version-script echo test.exec ; then
    expect_data version version.info '^VER:src/com/example/Widget.java$'
    expect_data version version.info '^VER:src/com/example/Helper.java$'
    #  and the data the version belongs to is all still there
    expect_data version version.info '^BRDA:5,0,0,1$'
    expect_data version version.info '^FNA:0,1,com.example.Widget.run()V$'
fi

# only an unset value is defaulted, so a caller who does not want the
#  computation can still say so
if run noversion 0 -o noversion.info -s src -c bin -jar $JAR \
       --java ./fakejava --version-script echo --rc compute_file_version=0 \
       test.exec ; then
    reject_data noversion noversion.info '^VER:'
fi

# and with no version script there is nothing to compute a version with, so
#  there is none in the result:  the default is not turned on for its own sake
if run noscript 0 -o noscript.info -s src -c bin -jar $JAR \
       --java ./fakejava test.exec ; then
    reject_data noscript noscript.info '^VER:'
fi

restore_permissions

if [ $STATUS == 0 ] ; then
    echo "Tests passed"
else
    echo "Tests failed"
fi
exit $STATUS
