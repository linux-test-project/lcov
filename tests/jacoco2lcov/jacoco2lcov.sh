#!/bin/bash
set +x

# ============================================================================
# jacoco2lcov is a wrapper:  it runs 'java -jar jacococli.jar report', then
#   xml2lcov, reads the xml2lcov result, then applies common LCOV options and
#   writes the result out.
#
# 'java' is a stub, written below.  It records the command line it was given
#   and writes a fixture report to the file named by '--xml', which lets this
#   test run on a machine with neither a JDK nor a JaCoCo installation, and
#   lets it check exactly what jacoco2lcov asked JaCoCo to do.
#
# Cases:
#   1. --help and the usage errors:  no .exec file, an unreadable one, no class
#      location, no source directory, one of its own options written in a way
#      Getopt::Long cannot use
#   2. jacococli.jar discovery:  --jar, JACOCOCLI_JAR, JACOCO_HOME (both
#      layouts), and the errors when each of those names nothing readable
#   3. the java command line:  the .exec files, one --classfiles per class
#      location, one --sourcefiles per source directory, and --xml
#   4. branch and function coverage are always generated by xml2lcov, so
#      jacoco2lcov defaults both of them on rather than let the read back in
#      drop them.
#   5. the common options are applied to the translated data:  the exclusions,
#      the filters and the comments reach the result, and an option
#      jacoco2lcov does not know is an error rather than something to forward
#   6. every argument which is not an option is an .exec file, whatever it
#      is called and wherever on the line it is - including after '--', which
#      ends the options
#   7. a run which asks nothing of the data produces what xml2lcov produced;
#      --xml keeps the intermediate report, and without it, it is temporary
#   8. -p expands an Eclipse/Maven plugin root, or a directory of them, into
#      the -s and -c options it implies - and with none of -s, -c and -p named,
#      the current directory is searched the same way
#   9. a failing subcommand is reported, whether it exited non-zero,
#      died on a signal, or could not be executed
#  10. the 'inconsistent' hint - the error a JaCoCo-derived report is
#      most likely to produce when it is read back in:
#        a covered line whose branches were all missed, and
#        a method which was never entered whose derived extent holds a
#         covered line
#  11. which java gets run:  --java, then $JAVA_HOME/bin/java, then the PATH
#  12. --verbose names each command before it runs, and --keep-going
#      reaches the step which understands it
#  13. -d names the directory to work in:  relative paths on the command line
#      are taken relative to it, an absolute path below it is recorded relative
#      to it and one outside it is not, and an execution data argument which
#      names a directory stands for the '.exec' files below it
#  14. the path the tool was invoked by decides where it looks for the tools it
#      runs:  a run through a link somewhere else still uses
#      the xml2lcov installed beside the script, and a run through a link whose
#      name is a Windows path - which is what a git-bash perl is handed - keeps
#      that name out of both the messages and the temporary directory
#  15. the tools are found on Windows too, where '-x' answers from the file name
#      extension:  a '.bat' beside the script is preferred and the extensionless
#      script is used anyway, while a name which is nothing at all is still an
#      error
#  16. a Windows path is translated to the name a git-bash, MSYS or Cygwin perl
#      can open - the mount point of the drive, and forward slashes - in every
#      path option, in the execution data arguments and in the name the script
#      was invoked by.  Either separator arrives, and so does a mixture of them,
#      a relative path and a UNC name;  a drive which is not mounted is left as
#      it stands
#  17. '--version-script' computes a version for the translated data, without
#      needing 'compute_file_version' to be asked for as well - and an explicit
#      'compute_file_version=0' still turns it off
# ============================================================================

