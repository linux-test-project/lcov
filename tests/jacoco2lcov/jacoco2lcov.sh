# write_source <path> <lines> -- a source file stand-in of the given length.
#  Nothing in this test compiles Java:  the sources exist because xml2lcov
#  drops a source file it cannot find, so the names in the fixture report have
#  to resolve to something
write_source()
{
    mkdir -p `dirname $1`
    local i=1
    while [ $i -le $2 ] ; do
        echo "// line $i"
        i=`expr $i + 1`
    done > $1
}

