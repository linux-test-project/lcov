#  backslashes, which neither FindBin nor basename() recognizes as one.  Such a
#  name is a legal file name here, so a link named that way asks the same
#  questions here that the failure asked there - is the tool which gets run the
#  one beside the script rather than one beside the name it was called by, and
#  does the name it was called by stay out of everything else.
#  'JACOCO2LCOV_TOOL' is what the harness runs, so it is what says how to invoke
#  the tool.  Coverage is turned off for these runs:  Devel::Cover records the
#  data under the path perl read the script from, and a second path to the same
#  script would be a second file in the coverage database
SAVED_JACOCO2LCOV_TOOL=$JACOCO2LCOV_TOOL
SAVED_COVER=$COVER
REALTOOL=`readlink -f $JACOCO2LCOV_TOOL`
REALBIN=`dirname $REALTOOL`
WINNAME='linkdir/S:\mtkoss\win\bin\jacoco2lcov'
